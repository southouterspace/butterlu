#!/usr/bin/env node
// Regenerates src/shapes.generated.ts from assets/frame-drawing.pdf.
// Needs poppler's pdftocairo on PATH. Run: bun run extract-geometry
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const pkgDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const repoDir = path.resolve(pkgDir, '../..');
const drawing = path.join(repoDir, 'assets/frame-drawing.pdf');
const options = JSON.parse(fs.readFileSync(path.join(repoDir, 'plans/product-options.json'), 'utf8'));
const outFile = path.join(pkgDir, 'src/shapes.generated.ts');

// pathIndex: the shape's outline and opening are paths N and N+1 in pdftocairo's SVG.
// originIn: the outline's top-left on the drawing's page, in inches.
// outerInsetIn: how far text must stay from the cut edge. The scalloped edge dips
// up to 0.24 in inward, so it needs more room than the rounded rectangle.
const SHAPES = [
  { id: 'rounded-rectangle', pathIndex: 18, originIn: [18.732, 2.117], outerInsetIn: 0.15 },
  { id: 'scalloped', pathIndex: 21, originIn: [18.662, 9.606], outerInsetIn: 0.35 },
];

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'frame-geom-'));
const svgFile = path.join(tmp, 'frame.svg');
execFileSync('pdftocairo', ['-svg', drawing, svgFile]);
const svgPaths = [...fs.readFileSync(svgFile, 'utf8').matchAll(/<path([^>]*)>/g)].map((m) => m[1]);
fs.rmSync(tmp, { recursive: true });

function toInches(index, [ox, oy]) {
  const attrs = svgPaths[index];
  const d = attrs.match(/ d="([^"]*)"/)[1];
  const [a, b, c, dd, e, f] = attrs.match(/matrix\(([^)]*)\)/)[1].split(/[ ,]+/).map(Number);
  const tokens = d.match(/[A-Za-z]|-?\d*\.?\d+(?:e-?\d+)?/g);
  const out = [];
  const points = [];
  let nums = [];
  const flush = () => {
    for (let k = 0; k < nums.length; k += 2) {
      const [x, y] = [nums[k], nums[k + 1]];
      const px = (a * x + c * y + e) / 72 - ox;
      const py = (b * x + dd * y + f) / 72 - oy;
      points.push([px, py]);
      out.push(px.toFixed(4), py.toFixed(4));
    }
    nums = [];
  };
  for (const t of tokens) {
    if (/[A-Za-z]/.test(t)) {
      flush();
      out.push(t);
    } else nums.push(Number(t));
  }
  flush();
  // pdftocairo closes each subpath with a trailing bare moveto, which pdf-lib rejects.
  const pathData = out.join(' ').replace(/ Z M [-\d. ]+$/, ' Z');
  const xs = points.map((p) => p[0]);
  const ys = points.map((p) => p[1]);
  return { pathData, minX: Math.min(...xs), maxX: Math.max(...xs), minY: Math.min(...ys), maxY: Math.max(...ys) };
}

const round = (n, step = 1 / 64) => Math.round(n / step) * step;

const rows = SHAPES.map(({ id, pathIndex, originIn, outerInsetIn }) => {
  const known = options.shapes.find((s) => s.id === id);
  if (!known) throw new Error(`plans/product-options.json has no shape ${id}`);
  const outline = toInches(pathIndex, originIn);
  const opening = toInches(pathIndex + 1, originIn);
  const borders = [opening.minX, opening.minY, known.widthIn - opening.maxX, known.heightIn - opening.maxY];
  const borderIn = round(Math.min(...borders));
  if (Math.max(...borders) - Math.min(...borders) > 0.02) {
    throw new Error(`${id}: border is not even on all sides (${borders.map((n) => n.toFixed(4)).join(', ')})`);
  }
  return {
    id,
    widthIn: known.widthIn,
    heightIn: known.heightIn,
    borderIn,
    outerInsetIn,
    outline: outline.pathData,
    opening: opening.pathData,
  };
});

const body = rows
  .map(
    (r) => `  '${r.id}': {
    widthIn: ${r.widthIn},
    heightIn: ${r.heightIn},
    borderIn: ${r.borderIn},
    outerInsetIn: ${r.outerInsetIn},
    outline: '${r.outline}',
    opening: '${r.opening}',
  },`,
  )
  .join('\n');

fs.writeFileSync(
  outFile,
  `// Generated by scripts/extract-geometry.mjs from assets/frame-drawing.pdf. Do not edit.
// Paths are SVG path data in frame-local inches, origin top-left, y down.
export const SHAPE_GEOMETRY = {
${body}
} as const;
`,
);
console.log(`wrote ${path.relative(repoDir, outFile)}: ${rows.map((r) => `${r.id} border ${r.borderIn}`).join(', ')}`);
