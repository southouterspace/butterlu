#!/usr/bin/env node
// Regenerates src/backgrounds.generated.ts: every background in
// plans/product-options.json with the text colour that contrasts best with the
// image's mean colour. Needs ImageMagick's `convert` on PATH.
// Run: bun run background-colors
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const pkgDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const repoDir = path.resolve(pkgDir, '../..');
const options = JSON.parse(fs.readFileSync(path.join(repoDir, 'plans/product-options.json'), 'utf8'));
const outFile = path.join(pkgDir, 'src/backgrounds.generated.ts');

const DARK = '#2b333f';
const LIGHT = '#ffffff';

const channel = (c) => {
  const s = c / 255;
  return s <= 0.03928 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4;
};
const luminance = ([r, g, b]) => 0.2126 * channel(r) + 0.7152 * channel(g) + 0.0722 * channel(b);
const hexRgb = (hex) => [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16));
const contrast = (a, b) => {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
};

function meanColor(file) {
  const out = execFileSync('convert', [file, '-resize', '1x1!', '-depth', '8', 'txt:-'], { encoding: 'utf8' });
  const m = out.match(/#([0-9A-Fa-f]{6})/);
  if (!m) throw new Error(`could not read mean colour of ${file}`);
  return hexRgb(`#${m[1]}`);
}

const rows = options.backgrounds
  .slice()
  .sort((a, b) => a.order - b.order)
  .map((bg) => {
    const mean = meanColor(path.join(repoDir, bg.file));
    const defaultTextColor = contrast(mean, hexRgb(DARK)) >= contrast(mean, hexRgb(LIGHT)) ? DARK : LIGHT;
    return { id: bg.id, name: bg.name, defaultTextColor };
  });

fs.writeFileSync(
  outFile,
  `// Generated by scripts/background-colors.mjs from plans/product-options.json. Do not edit.
// defaultTextColor is whichever of ${DARK} and ${LIGHT} contrasts more with the image's mean colour.
export const BACKGROUNDS = [
${rows.map((r) => `  { id: '${r.id}', name: ${JSON.stringify(r.name)}, defaultTextColor: '${r.defaultTextColor}' },`).join('\n')}
] as const;
`,
);
console.log(`wrote ${path.relative(repoDir, outFile)}: ${rows.length} backgrounds, ${rows.filter((r) => r.defaultTextColor === LIGHT).length} take light text`);
