// Writes public/_redirects: a 301 for every old Shopify product and collection URL,
// so nothing that once existed on butterlu.com 404s (docs/07 "URL continuity").
// Sources: plans/listing-map.json (Shopify handle -> clusters.json page),
// plans/decisions.json (built page or where an unbuilt page's URLs go),
// plans/catalog.json (Shopify collections). Rerun by `bun run build`.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { COLLECTIONS, PRODUCTS } from '../src/catalog/products.ts';

const siteDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const plans = (f) => JSON.parse(readFileSync(join(siteDir, '../../plans', f), 'utf8'));
const listingMap = plans('listing-map.json');
const decisions = plans('decisions.json');
const catalog = plans('catalog.json');

// The first page listed for a pageKey is its main page and takes its old URLs; later
// pages on the same pageKey are extra exact-search pages.
const productByPage = new Map();
for (const p of PRODUCTS) if (p.kind !== 'frame' && !productByPage.has(p.pageKey)) productByPage.set(p.pageKey, p);
const decisionByPage = new Map(decisions.rows.map((r) => [r.pageKey, r]));
const newProducts = new Set(PRODUCTS.map((p) => p.handle));
const newCollections = new Set(COLLECTIONS.map((c) => c.handle));

function targetForPage(pageKey, seen = new Set()) {
  if (!pageKey || seen.has(pageKey)) return '/collections/all';
  seen.add(pageKey);
  const p = productByPage.get(pageKey);
  if (p) return `/products/${p.handle}`;
  const to = decisionByPage.get(pageKey)?.redirectTo;
  if (!to) return '/collections/all';
  if (to.startsWith('collection:')) return `/collections/${to.slice('collection:'.length)}`;
  return targetForPage(to, seen);
}

// Old Shopify collections with no same-named collection here.
const COLLECTION_MAP = {
  frontpage: '/',
  'grandpa-papa-pop': '/collections/grandparent-frames',
  'pregnancy-baby': '/collections/baby-frames',
  'pet-frames': '/collections/pet-loss-memorial',
  'mom-dad-frames': '/collections/all',
  'mom-dad-frames-1': '/collections/all',
  'healing-affirmation': '/collections/all',
  'pet-ornament-car-hugs': '/collections/all',
  'photo-blocks-clip-frames': '/collections/all',
  'teacher-nanny-coach': '/collections/all',
};

const lines = [];
for (const row of listingMap.rows) {
  if (newProducts.has(row.shopifyHandle)) continue;
  lines.push(`/products/${row.shopifyHandle} ${targetForPage(row.pageKey)} 301`);
}
for (const c of catalog.collections) {
  if (newCollections.has(c.handle) || c.handle === 'all') continue;
  lines.push(`/collections/${c.handle} ${COLLECTION_MAP[c.handle] ?? '/collections/all'} 301`);
}
// Shopify's own pages that searchers and old links may still carry.
lines.push('/collections /collections/all 301', '/products /collections/all 301', '/pages/contact /pages/faq 301');

if (lines.length > 2000) throw new Error(`_redirects has ${lines.length} rules; Workers static assets allow 2,000`);
writeFileSync(join(siteDir, 'public/_redirects'), `# Generated by scripts/redirects.mjs. Do not edit.\n${lines.join('\n')}\n`);
console.log(`redirects: ${lines.length} rules`);
